/**
 * Quarterly access review (Phase 9, plan item 5).
 *
 *   node scripts/access-review.mjs            # print it
 *   node scripts/access-review.mjs --save     # also write it to docs/security/
 *
 * ---------------------------------------------------------------------------
 * The point of an access review is not the list - it is the questions the list
 * forces: does this person still work here, do they still need that role, and
 * why has nobody logged into that account since August?
 *
 * So this leads with the findings and puts the full table underneath. A report
 * that opens with 12 rows of healthy accounts buries the one that matters.
 *
 * Read it once a quarter, and whenever someone leaves.
 * ---------------------------------------------------------------------------
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import 'dotenv/config';
import { PrismaClient } from '@prisma/client';

const SAVE = process.argv.includes('--save');
const prisma = new PrismaClient();

/** Roles that can change money, people or permissions. */
const PRIVILEGED = new Set(['DEVELOPER', 'ADMIN', 'OWNER']);
const DORMANT_DAYS = 90;

const ist = (d) =>
  d ? new Date(d).toLocaleDateString('en-IN', { timeZone: 'Asia/Kolkata' }) : 'never';
const daysSince = (d) => (d ? Math.floor((Date.now() - new Date(d).getTime()) / 86400000) : null);

try {
  const users = await prisma.user.findMany({
    orderBy: [{ role: 'asc' }, { username: 'asc' }],
    select: {
      id: true, name: true, username: true, role: true, email: true,
      mfaEnabledAt: true, lastLoginAt: true, disabledAt: true,
      passwordChangedAt: true, mustChangePassword: true, createdAt: true,
      _count: { select: { sessions: true } },
    },
  });

  const active = users.filter((u) => !u.disabledAt);
  const findings = [];

  for (const u of active) {
    if (PRIVILEGED.has(u.role) && !u.mfaEnabledAt) {
      findings.push(`${u.username} (${u.role}) has no two-factor set up`);
    }
    if (!u.lastLoginAt) {
      findings.push(`${u.username} (${u.role}) has never logged in - created ${ist(u.createdAt)}`);
    } else if (daysSince(u.lastLoginAt) > DORMANT_DAYS) {
      findings.push(
        `${u.username} (${u.role}) last logged in ${daysSince(u.lastLoginAt)} days ago`
      );
    }
    if (daysSince(u.passwordChangedAt) > 365) {
      findings.push(`${u.username} has not changed their password in over a year`);
    }
  }
  for (const u of users.filter((x) => x.disabledAt)) {
    if (u._count.sessions > 0) {
      // Should be impossible - disabling revokes sessions - so if it appears,
      // something has gone wrong with that guarantee.
      findings.push(
        `${u.username} is DISABLED but still has ${u._count.sessions} session(s) - investigate`
      );
    }
  }

  const lines = [];
  const push = (s = '') => lines.push(s);

  push(`# Access review — ${ist(new Date())}`);
  push();
  push(`${users.length} account(s): ${active.length} active, ${users.length - active.length} disabled.`);
  push();

  push('## Findings');
  push();
  if (findings.length === 0) {
    push('Nothing to raise.');
  } else {
    for (const f of findings) push(`- ${f}`);
  }
  push();

  push('## Accounts');
  push();
  push('| User | Role | 2FA | Last login | Sessions | Status |');
  push('|---|---|---|---|---|---|');
  for (const u of users) {
    const ago = daysSince(u.lastLoginAt);
    push(
      `| ${u.name} (\`${u.username}\`) | ${u.role} | ${u.mfaEnabledAt ? 'yes' : '**no**'} | ` +
        `${ist(u.lastLoginAt)}${ago !== null ? ` (${ago}d)` : ''} | ${u._count.sessions} | ` +
        `${u.disabledAt ? `disabled ${ist(u.disabledAt)}` : 'active'} |`
    );
  }
  push();
  push('## What to do with this');
  push();
  push('- Anyone who has left: Settings → Users → Disable. That revokes every session at once.');
  push('- A privileged role without two-factor is the finding worth acting on first.');
  push('- A dormant account is a credential nobody is watching. Disable it; re-enabling is easy.');
  push();
  push('_Generated by `server/scripts/access-review.mjs`. Roles and permissions are enforced on');
  push('the server — see `src/lib/routePermissions.ts`._');

  const text = lines.join('\n');
  console.log(text);

  if (SAVE) {
    const dir = path.resolve('..', 'docs', 'security');
    mkdirSync(dir, { recursive: true });
    const file = path.join(dir, `ACCESS-REVIEW-${new Date().toISOString().slice(0, 10)}.md`);
    writeFileSync(file, `${text}\n`);
    console.log(`\nwritten to ${file}`);
  }
} finally {
  await prisma.$disconnect();
}
